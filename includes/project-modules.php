/**
 * Map the background choice to a class.
 *
 * 'palette9' is special: it defers to Kadence's own global-palette class rather
 * than a hex of ours, so the ticket band keeps whatever colour palette 9 is set
 * to and follows it if the palette changes. `has-background` is required
 * alongside it or Kadence's rule does not apply.
 */
function anspm_bg_class( $bg ) {
	if ( 'palette9' === $bg ) {
		return 'anspm-band--palette9 has-theme-palette-9-background-color has-background';
	}
	$allowed = array( 'cream', 'white', 'navy' );
	$bg      = in_array( $bg, $allowed, true ) ? $bg : 'cream';
	return 'anspm-band--' . $bg;
}

/** Shared band open/close so every module is structurally identical. */
function anspm_band_open( $bg, $extra_class = '' ) {
	return '<section class="anspm-band ' . esc_attr( anspm_bg_class( $bg ) )
		. ( $extra_class ? ' ' . esc_attr( $extra_class ) : '' )
		. '"><div class="anspm-band__inner">';
}

function anspm_band_close() {
	return '</div></section>';
}

/** Figure markup for an attachment id. */
function anspm_figure( $image_id, $caption = '', $class = '' ) {
	if ( ! $image_id ) { return ''; }

	$img = wp_get_attachment_image(
		$image_id,
		'large',
		false,
		array( 'class' => 'anspm-figure__img' )
	);
	if ( ! $img ) { return ''; }

	$out  = '<figure class="anspm-figure' . ( $class ? ' ' . esc_attr( $class ) : '' ) . '">';
	$out .= $img;
	if ( '' !== trim( (string) $caption ) ) {
		$out .= '<figcaption class="anspm-figure__caption">' . esc_html( $caption ) . '</figcaption>';
	}
	$out .= '</figure>';

	return $out;
}

function anspm_render_program_story() {
	if ( get_sub_field( 'hidden' ) ) { return ''; }

	$eyebrow  = (string) get_sub_field( 'eyebrow' );
	$heading  = (string) get_sub_field( 'heading' );
	$body     = (string) get_sub_field( 'body' );
	$image    = (int) get_sub_field( 'image' );
	$position = (string) get_sub_field( 'image_position' );
	$caption  = (string) get_sub_field( 'caption' );
	$bg       = (string) get_sub_field( 'background' );

	$figure = anspm_figure( $image, $caption, 'anspm-figure--' . ( $position ? $position : 'below' ) );

	$out = anspm_band_open( $bg, 'anspm-story' );

	if ( '' !== trim( $eyebrow ) ) {
		$out .= '<p class="anspm-eyebrow">' . esc_html( $eyebrow ) . '</p>';
	}
	if ( '' !== trim( $heading ) ) {
		$out .= '<h2 class="anspm-heading">' . wp_kses_post( $heading ) . '</h2>';
	}

	if ( 'above' === $position ) { $out .= $figure; }

	$out .= '<div class="anspm-body">';
	// Float positions must sit INSIDE the text flow or there is nothing to wrap.
	if ( 'left' === $position || 'right' === $position ) { $out .= $figure; }
	$out .= wp_kses_post( $body );
	$out .= '</div>';

	if ( 'below' === $position || 'wide' === $position ) { $out .= $figure; }

	$out .= anspm_band_close();

	return $out;
}

function anspm_render_guest_artist() {
	if ( get_sub_field( 'hidden' ) ) { return ''; }

	$eyebrow  = (string) get_sub_field( 'eyebrow' );
	$name     = (string) get_sub_field( 'name' );
	$role     = (string) get_sub_field( 'role' );
	$portrait = (int) get_sub_field( 'portrait' );
	$bio      = (string) get_sub_field( 'bio' );
	$second   = (int) get_sub_field( 'second_image' );
	$label    = (string) get_sub_field( 'link_label' );
	$url      = (string) get_sub_field( 'link_url' );
	$bg       = (string) get_sub_field( 'background' );

	$out = anspm_band_open( $bg, 'anspm-artist' );

	if ( '' !== trim( $eyebrow ) ) {
		$out .= '<p class="anspm-eyebrow">' . esc_html( $eyebrow ) . '</p>';
	}
	if ( '' !== trim( $name ) ) {
		$out .= '<h2 class="anspm-heading">' . wp_kses_post( $name ) . '</h2>';
	}
	if ( '' !== trim( $role ) ) {
		$out .= '<p class="anspm-artist__role">' . wp_kses_post( $role ) . '</p>';
	}

	$out .= '<div class="anspm-body">';
	$out .= anspm_figure( $portrait, '', 'anspm-figure--portrait' );
	$out .= wp_kses_post( $bio );
	$out .= '</div>';

	$out .= anspm_figure( $second, '', 'anspm-figure--wide' );

	if ( '' !== trim( $label ) && '' !== trim( $url ) ) {
		$out .= '<p class="anspm-actions"><a class="anspm-cta" href="' . esc_url( $url ) . '">'
			. esc_html( $label ) . '</a></p>';
	}

	$out .= anspm_band_close();

	return $out;
}

/**
 * Tickets band.
 *
 * The anchor id matters more than it looks: the Project Template's hero CTA
 * defaults to href="#tickets", so a page whose ticket band has no such id gets
 * a button that goes nowhere. Hence the id lives on the <section> itself and is
 * a field rather than a hard-coded string.
 *
 * do_shortcode() rather than embedding markup — the ticket UI belongs to
 * ars-nova-ticketing-bridge and must stay its responsibility.
 */
function anspm_render_tickets() {
	if ( get_sub_field( 'hidden' ) ) { return ''; }

	$heading = (string) get_sub_field( 'heading' );
	$anchor  = sanitize_title( (string) get_sub_field( 'anchor' ) );
	$note    = (string) get_sub_field( 'note' );
	$bg      = (string) get_sub_field( 'background' );

	if ( '' === $anchor ) { $anchor = 'tickets'; }
	if ( '' === trim( $heading ) ) { $heading = 'Choose your night'; }

	$shortcode = sprintf(
		'[ans_event_tickets heading="%s"]',
		esc_attr( str_replace( '"', '', $heading ) )
	);

	$out  = '<section id="' . esc_attr( $anchor ) . '" class="anspm-band anspm-tickets '
		. esc_attr( anspm_bg_class( $bg ) ) . '"><div class="anspm-band__inner">';
	$out .= do_shortcode( $shortcode );
	if ( '' !== trim( $note ) ) {
		$out .= '<div class="anspm-tickets__note">' . wp_kses_post( $note ) . '</div>';
	}
	$out .= '</div></section>';

	return $out;
}

/**
 * Notice for a layout that has no renderer. Visible to editors only.
 */
function anspm_render_missing( $layout ) {
	if ( ! current_user_can( 'edit_posts' ) ) {
		return '';
	}
	return '<section class="anspm-band anspm-band--cream anspm-missing"><div class="anspm-band__inner">'
		. '<p class="anspm-missing__msg"><strong>Module type &ldquo;'
		. esc_html( $layout )
		. '&rdquo; has no renderer yet.</strong> Its content is saved but nothing draws it. '
		. 'Only logged-in editors can see this message.</p>'
		. '</div></section>';
}

/**
 * Build every module for a page.
 *
 * @param int $post_id Page ID.
 * @return string
 */
function anspm_render_modules( $post_id ) {
	if ( ! function_exists( 'have_rows' ) ) { return ''; }
	if ( ! have_rows( 'ans_project_modules', $post_id ) ) { return ''; }

	$out = '';

	while ( have_rows( 'ans_project_modules', $post_id ) ) {
		the_row();
		switch ( get_row_layout() ) {
			case 'program_story':
				$out .= anspm_render_program_story();
				break;
			case 'guest_artist':
				$out .= anspm_render_guest_artist();
				break;
			case 'tickets':
				$out .= anspm_render_tickets();
				break;
			default:
				// FAIL LOUDLY. A layout with no renderer is exactly how Ligature's 18
				// "Content Blocks" layouts sat dead for years: the data saved perfectly
				// and nothing ever drew it, with no error anywhere. Editors see this;
				// the public never does.
				$out .= anspm_render_missing( (string) get_row_layout() );
				break;
		}
	}

	return $out;
}

/**
 * Append modules to the page content.
 *
 * Priority 8 — deliberately BEFORE ars-nova-core's project template filter at 9,
 * so that filter wraps hero/support around content-plus-modules rather than
 * around content alone. Net order: hero → blocks → modules → support.
 *
 * The three loop guards mirror the Project Template's, and for the same reason:
 * the_content also fires for excerpts, feeds and SEO description generation.
 */
add_filter(
	'the_content',
	function ( $content ) {
		if ( ! is_singular( 'page' ) || ! in_the_loop() || ! is_main_query() ) {
			return $content;
		}

		$post = get_post();
		if ( ! $post || ! anspm_is_project_page( $post->ID ) ) {
			return $content;
		}

		return $content . anspm_render_modules( $post->ID );
	},
	8
);

/* ---------------------------------------------------------------------------
 * REST — read and write a page's modules.
 *
 * WHY THIS EXISTS. Flexible-content rows are not ordinary post meta. ACF stores
 * a serialised layout list in the parent key plus a `_`-prefixed field-key
 * reference beside EVERY sub-value. Writing those by hand through a generic
 * meta tool does not work — wp_set_page_meta silently drops unregistered keys
 * and still answers 200, so the page renders unchanged and nothing reports an
 * error. (Confirmed the hard way on 2026-08-15; same species as the wiki's
 * failure #8.) These routes go through ACF's own update_field(), which is the
 * only supported way to write this shape.
 * ------------------------------------------------------------------------ */

add_action( 'rest_api_init', function () {
	register_rest_route( 'ans-ops/v1', '/project-modules/(?P<id>\d+)', array(
		array(
			'methods'             => 'GET',
			'permission_callback' => function () { return current_user_can( 'edit_pages' ); },
			'callback'            => 'anspm_route_get_modules',
		),
		array(
			'methods'             => 'POST',
			'permission_callback' => function () { return current_user_can( 'edit_pages' ); },
			'callback'            => 'anspm_route_set_modules',
		),
	) );
} );

function anspm_route_get_modules( WP_REST_Request $req ) {
	$id = (int) $req['id'];
	if ( ! get_post( $id ) ) {
		return new WP_Error( 'anspm_no_page', 'No such page.', array( 'status' => 404 ) );
	}
	if ( ! function_exists( 'get_field' ) ) {
		return new WP_Error( 'anspm_no_acf', 'ACF is not active.', array( 'status' => 409 ) );
	}
	$rows = get_field( 'ans_project_modules', $id );

	return array(
		'ok'               => true,
		'page'             => $id,
		'title'            => get_the_title( $id ),
		'project_template' => anspm_is_project_page( $id ),
		'count'            => is_array( $rows ) ? count( $rows ) : 0,
		'modules'          => is_array( $rows ) ? $rows : array(),
		'site'             => home_url(),
		'is_production'    => anspm_is_production(),
	);
}

/** Same production posture as the rest of the Ars Nova plugins. */
function anspm_is_production() {
	if ( function_exists( 'ans_ops_is_production' ) ) {
		return ans_ops_is_production();
	}
	$host = wp_parse_url( home_url(), PHP_URL_HOST );
	return in_array( strtolower( (string) $host ), array( 'arsnovasingers.org', 'www.arsnovasingers.org' ), true );
}

/** Sub-fields we accept per layout. Anything else in the payload is ignored. */
function anspm_allowed_subfields() {
	return array(
		'program_story' => array( 'hidden', 'eyebrow', 'heading', 'body', 'image', 'image_position', 'caption', 'background' ),
		'guest_artist'  => array( 'hidden', 'eyebrow', 'name', 'role', 'portrait', 'bio', 'second_image', 'link_label', 'link_url', 'background' ),
		'tickets'       => array( 'hidden', 'heading', 'anchor', 'note', 'background' ),
	);
}

function anspm_route_set_modules( WP_REST_Request $req ) {
	$id = (int) $req['id'];

	if ( ! get_post( $id ) ) {
		return new WP_Error( 'anspm_no_page', 'No such page.', array( 'status' => 404 ) );
	}
	if ( ! function_exists( 'update_field' ) ) {
		return new WP_Error( 'anspm_no_acf', 'ACF is not active.', array( 'status' => 409 ) );
	}
	if ( anspm_is_production() && ! filter_var( $req->get_param( 'confirm_production' ), FILTER_VALIDATE_BOOLEAN ) ) {
		return new WP_Error( 'anspm_production_blocked', 'This is the production site. Resend with confirm_production=true to proceed.', array( 'status' => 403 ) );
	}

	$modules = $req->get_param( 'modules' );
	if ( ! is_array( $modules ) ) {
		return new WP_Error( 'anspm_bad_payload', 'Provide "modules" as an array of rows, each with acf_fc_layout.', array( 'status' => 400 ) );
	}

	$allowed = anspm_allowed_subfields();
	$rows    = array();
	$skipped = array();

	foreach ( $modules as $i => $module ) {
		if ( ! is_array( $module ) || empty( $module['acf_fc_layout'] ) ) {
			$skipped[] = array( 'index' => $i, 'why' => 'missing acf_fc_layout' );
			continue;
		}
		$layout = (string) $module['acf_fc_layout'];
		if ( ! isset( $allowed[ $layout ] ) ) {
			$skipped[] = array( 'index' => $i, 'why' => 'unknown layout "' . $layout . '"' );
			continue;
		}

		$row = array( 'acf_fc_layout' => $layout );
		foreach ( $allowed[ $layout ] as $sub ) {
			if ( array_key_exists( $sub, $module ) ) {
				$row[ $sub ] = $module[ $sub ];
			}
		}
		$rows[] = $row;
	}

	// Field KEY, not name — update_field() is far more reliable with the key.
	$result = update_field( 'field_anspm_modules', $rows, $id );

	// Verify rather than trust: read it straight back out.
	$readback = function_exists( 'get_field' ) ? get_field( 'ans_project_modules', $id ) : null;
	$written  = is_array( $readback ) ? count( $readback ) : 0;

	if ( count( $rows ) !== $written ) {
		return new WP_REST_Response( array(
			'ok'       => false,
			'error'    => 'Write did not verify: sent ' . count( $rows ) . ' rows, read back ' . $written . '.',
			'result'   => $result,
			'skipped'  => $skipped,
		), 500 );
	}

	return array(
		'ok'            => true,
		'page'          => $id,
		'title'         => get_the_title( $id ),
		'written'       => $written,
		'layouts'       => wp_list_pluck( $rows, 'acf_fc_layout' ),
		'skipped'       => $skipped,
		'site'          => home_url(),
		'is_production' => anspm_is_production(),
	);
}

/**
 * Stylesheet, only on project pages.
 */
add_action(
	'wp_enqueue_scripts',
	function () {
		if ( ! is_singular( 'page' ) || ! anspm_is_project_page( get_queried_object_id() ) ) {
			return;
		}
		wp_enqueue_style(
			'ans-project-modules',
			plugins_url( 'assets/css/project-modules.css', ARS_NOVA_CORE_DIR . 'ars-nova-core.php' ),
			array(),
			ANSPM_VERSION
		);
	}
);

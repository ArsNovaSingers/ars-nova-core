/*
 * Fields are still registered in PHP here. That is a KNOWN INTERIM STATE, not a
 * decision - the field group is to be exported from ACF's own Tools > Export
 * (so the JSON is generated by ACF rather than hand-written) and committed to
 * acf-json/, after which this registration block is deleted and the group
 * becomes editable in the admin like every other group. Field key
 * field_anspm_modules and field name ans_project_modules must survive that move
 * unchanged or every module already saved on a page silently stops resolving.
 */

/* ---------------------------------------------------------------------------
 * Is this page on the Project Template?
 *
 * Prefers ars-nova-core's own helper so there is ONE definition. The fallback
 * exists only so this plugin degrades to "renders nothing" rather than fatals
 * if core is deactivated.
 * ------------------------------------------------------------------------ */
function anspm_is_project_page( $post_id ) {
	if ( function_exists( 'arsnova_is_project_template' ) ) {
		return arsnova_is_project_template( $post_id );
	}
	return 'ans-project-template.php' === get_page_template_slug( $post_id );
}


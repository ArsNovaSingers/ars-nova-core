/**
 * Project Modules - reusable content sections for the Project Template.
 *
 * A small library of blended title/text/image blocks (Program Story, Guest
 * Artist, Tickets) that each concert page assembles, reorders and toggles per
 * page. Renders at the_content priority 8, one before project-template.php's
 * filter at 9, so output lands as hero -> page blocks -> modules -> Support.
 *
 * Absorbed into ars-nova-core in 1.9.0 from the standalone plugin
 * ars-nova-project-modules, which is retired. Renderers belong in this plugin
 * for the same reason the CPTs do: the previous agency's 18 Flexible Content
 * layouts still hold data and draw nothing, because their renderers lived in
 * the StageHand theme and died with it.
 */

